#set -o xtrace
set -o errexit
set -o pipefail
set -o nounset

bin="$(cd "$(dirname "$0")" > /dev/null; pwd)"

readonly marker="This script is autogenerated by the Apache Cassandra build"
readonly manifest_name=".installed-by-cassandra-build"

# Hooks whose input is on stdin, which the dispatcher must replay to each script
reads_stdin() {
  [[ "$1" == pre-push || "$1" == post-rewrite ]]
}

# Scripts installed before the build recorded what it installed (see $manifest_name)
legacy_scripts() {
  case "$1" in
    post-checkout|post-switch) echo "100-update-submodules.sh" ;;
    pre-commit)                echo "100-verify-submodules-pushed.sh" ;;
  esac
}

install_dispatcher() {
  local -r name="$1"
  local -r script_name="$2"
  local stdin_setup="" stdin_redirect=""
  if reads_stdin "$name"; then
    stdin_setup="input=\"\$(mktemp)\"
trap 'rm -f \"\$input\"' EXIT
cat > \"\$input\""
    stdin_redirect=' < "$input"'
  fi

  cat <<EOF > "$script_name"
#!/usr/bin/env bash

# $marker; DO NOT CHANGE!
# When this script is not found it will be installed automatically by the build.
# It runs every script in ${name}.d in order of their numeric prefix, stopping at the first to fail.
# A hook found when this script was first installed was relocated to ${name}.d/000-original.sh

# Redirect output to stderr.
exec 1>&2

# resolved when run, so that linked worktrees (where .git is a file) and core.hooksPath work
d_dir="\$(git rev-parse --git-path hooks)/${name}.d"
[[ -d "\$d_dir" ]] || exit 0
${stdin_setup}

# read via fd 3, so that the scripts cannot consume the list
while IFS= read -r path <&3; do
  "\$path" "\$@"${stdin_redirect} || exit \$?
done 3< <(find "\$d_dir" -maxdepth 1 -name '*.sh' | perl -e "print sort{(split '/', \\\$a)[-1] <=> (split '/', \\\$b)[-1]}<>")
EOF
  chmod a+x "$script_name"
}

# Remove the scripts this build installed in $1 for hook $2 that are no longer provided ($3, one per line)
remove_stale_scripts() {
  local -r d_dir="$1"
  local -r name="$2"
  local -r provided="$3"
  local previous script
  if [[ -f "$d_dir/$manifest_name" ]]; then
    previous="$(cat "$d_dir/$manifest_name")"
  else
    previous="$(legacy_scripts "$name")"
  fi
  for script in $previous; do
    if ! grep -qxF "$script" <<< "$provided"; then
      rm -f "$d_dir/$script"
    fi
  done
}

install_hook() {
  local -r hooks_dir="$1"
  local -r name="$2"
  local -r trigger_on_install=$3
  local -r d_dir="${hooks_dir}/${name}.d"
  local -r script_name="${hooks_dir}/${name}"
  local -r src_dir="$bin/git-hooks/${name}"

  mkdir -p "$d_dir"
  local installed=true
  if [[ -e "$script_name" ]]; then
    if grep -q "$marker" "$script_name" &> /dev/null; then
      installed=false
    elif [[ -e "$d_dir/000-original.sh" ]]; then
      echo "$script_name was not generated by the Apache Cassandra build, and ${d_dir}/000-original.sh already exists; please merge them" 1>&2
      exit 1
    else
      echo "$script_name was not generated by the Apache Cassandra build; relocating it to ${d_dir}/000-original.sh" 1>&2
      mv "$script_name" "$d_dir/000-original.sh"
    fi
  fi

  local -r provided="$(cd "$src_dir" && ls -1 -- *.sh)"
  remove_stale_scripts "$d_dir" "$name" "$provided"
  cp "$src_dir"/*.sh "$d_dir"/
  echo "$provided" > "$d_dir/$manifest_name"

  install_dispatcher "$name" "$script_name"
  if $installed && $trigger_on_install ; then
    echo "Running script $script_name"
    "$script_name"
  fi
}

# Remove a hook this build previously installed, but no longer provides
uninstall_hook() {
  local -r hooks_dir="$1"
  local -r name="$2"
  local -r d_dir="${hooks_dir}/${name}.d"
  local -r script_name="${hooks_dir}/${name}"

  if [[ -e "$script_name" ]] && grep -q "$marker" "$script_name" &> /dev/null; then
    rm -f "$script_name"
  fi
  if [[ -d "$d_dir" ]]; then
    remove_stale_scripts "$d_dir" "$name" ""
    rm -f "$d_dir/$manifest_name"
    rmdir "$d_dir" &> /dev/null || true
  fi
}

_install_hooks() {
  local hooks_dir
  # the directory git runs hooks from: the common dir's hooks (shared by all worktrees), unless core.hooksPath is set
  hooks_dir="$(git rev-parse --git-path hooks 2> /dev/null || true)"
  if [[ -z "${hooks_dir:-}" ]]; then
    # not in a git repo, noop
    return 0
  fi

  # make sure hooks directory exists; does not exist by default for worktrees
  mkdir -p "${hooks_dir}" &> /dev/null || true
  hooks_dir="$(cd "$hooks_dir" && pwd)"

  # shared by the hook scripts
  rm -rf "${hooks_dir}/cassandra-lib"
  cp -R "$bin/git-hooks/cassandra-lib" "${hooks_dir}/"

  install_hook "$hooks_dir" "post-checkout" true
  install_hook "$hooks_dir" "post-commit"   false
  install_hook "$hooks_dir" "post-merge"    false
  install_hook "$hooks_dir" "post-rewrite"  false
  install_hook "$hooks_dir" "pre-commit"    false
  install_hook "$hooks_dir" "pre-push"      false
  # git has no post-switch hook (git switch runs post-checkout), but earlier builds installed one
  uninstall_hook "$hooks_dir" "post-switch"
}

_git_config_set() {
  local -r name="$1"
  # only care about rc
  git config --local --get "$name" &> /dev/null
}

_install_configs() {
  # when doing pull, this makes sure submodules are updated
  _git_config_set submodule.recurse || git config --local submodule.recurse true
  # submodule.recurse would otherwise make git push recurse on demand, pushing each submodule with the superproject's
  # refspec and without --force; instead, the pre-push hook verifies the submodule commits are available upstream
  git config --get push.recurseSubmodules &> /dev/null || git config --local push.recurseSubmodules no
}

_main() {
  local git_dir
  # make sure to use --git-common-dir and not --git-dir to support worktrees
  git_dir="$(git rev-parse --git-common-dir 2> /dev/null || true)"
  # not in a git repo, noop
  [[ -z "${git_dir:-}" ]] && return 0

  _install_configs
  _install_hooks
}

_main "$@"
